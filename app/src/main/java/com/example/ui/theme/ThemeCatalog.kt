enum class ThemeUnlockType {
  FREE_DEFAULT,
  COINS,
  REAL_PURCHASE,
}

data class AppThemeDefinition(
  val id: String,
  val name: String,
  val subtitle: String,
  val isDark: Boolean,
  val unlockType: ThemeUnlockType,
  val coinCost: Int = 0,
  val priceUsdCents: Int = 0,
  val pricePkr: Int = 0,
  val colorScheme: ColorScheme,
  val kineticColors: KineticLabColors,
) {
  val formattedUsd: String
    get() = if (priceUsdCents <= 0) "Free" else "$${priceUsdCents / 100}.${(priceUsdCents % 100).toString().padStart(2, '0')}"

  val formattedPkr: String
    get() = if (pricePkr <= 0) "Free" else "Rs. ${"%,d".format(pricePkr)}"
}

